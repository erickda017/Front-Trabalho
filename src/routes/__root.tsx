function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="pt-BR">
      <head>
        <script dangerouslySetInnerHTML={{ __html: temaBootstrapScript }} />
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function AuthGate() {
  const { session } = useAppState();

  if (session === undefined) {
    return (
      <div className="bg-background text-subtle grid min-h-screen place-items-center text-sm">
        Carregando painel...
      </div>
    );
  }

  if (!session) return <LoginScreen />;

  // Required: nested routes render here. Removing <Outlet /> breaks all child routes.
  return <Outlet />;
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();

  return (
    <QueryClientProvider client={queryClient}>
      <TemaProvider>
        <AppStateProvider>
          <AuthGate />
          <Toaster />
        </AppStateProvider>
      </TemaProvider>
    </QueryClientProvider>
  );
}
